def _page_ref(page: Path, content_root: Path) -> dict[str, str]:
    """The page's doc identity as the site resolves it (content-core/identity)."""
    project, bucket, folder = (
        page.resolve().relative_to(content_root.resolve()).parts[:3]
    )
    slug = parse_page(page).meta.get("slug") or re.sub(r"^\d+-", "", folder)
    return {"project": project, "bucket": bucket, "slug": str(slug)}


def _evidence_ref(
    ev: Evidence, matrix: Matrix, content_root: Path
) -> dict[str, str] | None:
    page, _ = _source_page(ev.source, content_root / matrix.project)
    return _page_ref(page, content_root) if page else None


def _proof_json(proof: Proof, content_root: Path) -> dict[str, object]:
    claim = proof.claim
    return {
        "script": proof.script,
        "page": _page_ref(proof.page, content_root),
        "anchor": proof.anchor,
        "ready": proof.ready,
        "works": claim.works,
        "fails": claim.fails if isinstance(claim.fails, str) else None,
        "version": proof.version,
        "api": claim.api,
        "note": claim.note,
    }


def _tested_version(result: Result, matrix: Matrix, iface: str) -> str | None:
    """The one version the project's own claiming scripts pin, if they agree."""
    seen = {
        p.version
        for (project, key, _), cell in result.proofs.items()
        if project == matrix.project and key == iface
        for p in cell
        if p.project == project and p.version
    }
    return seen.pop() if len(seen) == 1 else None


_SPEC_EDGES = {"consumes", "implements"}


def _verified(proofs: list[Proof]) -> bool:
    return any(p.ready and p.claim.works for p in proofs)


def diagnostics(result: Result, matrix: Matrix) -> list[dict[str, Any]]:
    """Report-only gaps between what CI proves and what the model says.

    - ``unmodeled``: a CI-tested interface with no model element.
    - ``missing-edge``: an interface verifies journeys whose client
      ``consumes`` a spec, but has no ``consumes``/``implements`` edge to it.
      Journeys without requirements fall back to the matrix ``spec``.
    - ``unmigrated``: journeys with no asset or no requirements.
    - ``unverified-asset``: the matrix spec ``governs`` an asset no verified
      journey acts on.
    - ``missing-asset-edge``: an interface verifies a journey on an asset, but
      its implementation has no ``operatesOn`` edge to that asset.
    - ``unverified-asset-edge``: a modeled implementation ``operatesOn`` an
      asset, but no ready working proof in this matrix exercises the edge.
    """
    model = result.model
    found: list[dict[str, Any]] = []
    tested: set[str] = set()
    missing: dict[tuple[str, str], list[str]] = {}
    missing_assets: dict[tuple[str, str, str], list[str]] = {}
    verified_assets: set[tuple[str, str]] = set()
    for (project, iface, jid), proofs in sorted(result.proofs.items()):
        if project != matrix.project or not any(p.ready for p in proofs):
            continue
        tested.add(iface)
        entry, journey = matrix.interfaces[iface], matrix.journeys[jid]
        if entry.model is None or not model.kinds:
            continue
        if _verified(proofs) and journey.asset:
            if model.has({"operatesOn"}, entry.model, journey.asset):
                verified_assets.add((entry.model, journey.asset))
            else:
                missing_assets.setdefault(
                    (iface, entry.model, journey.asset), []
                ).append(jid)
        if journey.requires:
            if not _verified(proofs):
                continue
            needed = (journey.requires.get("client") or {}).get("consumes", ())
        else:
            needed = (matrix.spec,) if matrix.spec else ()
        for spec in needed:
            if not model.has(_SPEC_EDGES, entry.model, spec):
                missing.setdefault((iface, spec), []).append(jid)
    for iface in sorted(tested):
        if matrix.interfaces[iface].model is None:
            found.append({"kind": "unmodeled", "interface": iface})
    for (iface, spec), journeys in sorted(missing.items()):
        found.append(
            {
                "kind": "missing-edge",
                "interface": iface,
                "source": matrix.interfaces[iface].model,
                "target": spec,
                "journeys": journeys,
            }
        )
    for (iface, source, asset), journeys in sorted(missing_assets.items()):
        found.append(
            {
                "kind": "missing-asset-edge",
                "interface": iface,
                "source": source,
                "asset": asset,
                "journeys": journeys,
            }
        )
    unmigrated = [
        j.id for j in matrix.journeys.values() if not (j.asset and j.requires)
    ]
    if unmigrated:
        found.append({"kind": "unmigrated", "journeys": unmigrated})
    if matrix.spec and model.kinds:
        journey_assets = {
            matrix.journeys[jid].asset
            for (project, _, jid), proofs in result.proofs.items()
            if project == matrix.project and _verified(proofs)
        }
        for kind, source, target in sorted(model.edges):
            if (
                kind == "governs"
                and source == matrix.spec
                and target not in journey_assets
            ):
                found.append({"kind": "unverified-asset", "asset": target})
    modeled_interfaces = {
        entry.model for entry in matrix.interfaces.values() if entry.model is not None
    }
    matrix_assets = {journey.asset for journey in matrix.journeys.values()}
    for kind, source, target in sorted(model.edges):
        if (
            kind == "operatesOn"
            and source in modeled_interfaces
            and target in matrix_assets
            and (source, target) not in verified_assets
        ):
            found.append(
                {
                    "kind": "unverified-asset-edge",
                    "source": source,
                    "asset": target,
                }
            )
    return found


def verified_edges(result: Result, matrix: Matrix) -> list[dict[str, object]]:
    """Model contract and asset-breadth edges exercised by gating claims."""
    model = result.model
    edges: dict[tuple[str, str, str], dict[str, set[str]]] = {}
    for (project, iface, jid), proofs in result.proofs.items():
        entry = matrix.interfaces.get(iface)
        if project != matrix.project or entry is None or entry.model is None:
            continue
        if not _verified(proofs):
            continue
        consumes = (matrix.journeys[jid].requires.get("client") or {}).get(
            "consumes", ()
        )
        for spec in consumes:
            kind = model.has(_SPEC_EDGES, entry.model, spec)
            if kind:
                seen = edges.setdefault(
                    (entry.model, kind, spec), {"journeys": set(), "interfaces": set()}
                )
                seen["journeys"].add(jid)
                seen["interfaces"].add(iface)
        asset = matrix.journeys[jid].asset
        if asset and model.has({"operatesOn"}, entry.model, asset):
            used = edges.setdefault(
                (entry.model, "operatesOn", asset),
                {"journeys": set(), "interfaces": set()},
            )
            used["journeys"].add(jid)
            used["interfaces"].add(iface)
    return [
        {
            "source": source,
            "kind": kind,
            "target": target,
            "interfaces": sorted(seen["interfaces"]),
            "journeys": sorted(seen["journeys"]),
        }
        for (source, kind, target), seen in sorted(edges.items())
    ]


def artifact(result: Result, matrix: Matrix, content_root: Path) -> dict[str, object]:
    """The matrix with every cell resolved, draft claims included and flagged."""
    engine_pages = _engine_pages(content_root)
    journeys = []
    for journey in matrix.journeys.values():
        cells: dict[str, object] = {}
        for iface in matrix.interfaces:
            found = cell(result, matrix, iface, journey.id, drafts=True)
            every = result.proofs.get((matrix.project, iface, journey.id), [])
            if found.status == "unknown" and not every:
                continue
            cells[iface] = {
                "status": found.status,
                "draft": found.draft,
                "proofs": [_proof_json(p, content_root) for p in every],
                "evidence": [
                    {
                        "outcome": e.outcome,
                        "page": _evidence_ref(e, matrix, content_root),
                        "why": e.why,
                        "source": e.source,
                        "api": e.api.get(iface),
                        "verified": e.verified.get(iface),
                        "note": e.note,
                    }
                    for e in found.evidence
                ],
            }
        journeys.append(
            {
                "id": journey.id,
                "title": journey.title,
                "summary": journey.summary,
                "request": journey.request,
                "family": journey.family,
                "asset": journey.asset,
                "requires": {
                    role: {edge: list(ids) for edge, ids in edges.items()}
                    for role, edges in journey.requires.items()
                },
                "cells": cells,
            }
        )
    return {
        "generated": "by `uv run docsnip compat --fix`; edit compatibility.yml "
        "and script claims, not this file",
        "version": ARTIFACT_VERSION,
        "project": matrix.project,
        "spec": matrix.spec,
        "interfaces": [
            {
                "key": i.key,
                "label": i.label,
                "version": (matrix.pins.get(i.pin) if i.pin else None)
                or _tested_version(result, matrix, i.key),
                "package": i.package,
                "model": i.model,
            }
            for i in matrix.interfaces.values()
        ],
        "tables": [
            {
                "id": t.id,
                "title": t.title,
                "columns": list(t.columns),
                "rows": list(t.rows),
            }
            for t in matrix.tables.values()
        ],
        "assets": [
            {
                "id": t.id[len(_ROLLUP) :],
                "title": t.title,
                "columns": list(t.columns),
                "rows": list(t.rows),
            }
            for t in asset_groups(matrix, result.model)
        ],
        "engines": [
            {
                "id": e.id,
                "title": e.title,
                "interfaces": list(e.interfaces),
                "page": _page_ref(found[0], content_root) if found else None,
                "anchor": found[1].id if found and found[1] else None,
                "heading": found[1].text if found and found[1] else None,
                "groups": [
                    {"table": g.id, "columns": list(g.columns), "rows": list(g.rows)}
                    for g in e.groups
                ],
            }
            for e in engines(matrix, result.model)
            for found in [engine_pages.get((matrix.project, e.id))]
        ],
        "journeys": journeys,
        "verifiedEdges": verified_edges(result, matrix),
        "diagnostics": diagnostics(result, matrix),
    }


def _artifacts(repo_root: Path, result: Result) -> Iterable[tuple[Path, str, str]]:
    """Each matrix's artifact: its path, current text, and rendered text."""
    content_root = repo_root / "content"
    for matrix in result.matrices.values():
        path = matrix.path.parent / ARTIFACT
        old = path.read_text() if path.is_file() else ""
        new = (
            json.dumps(
                artifact(result, matrix, content_root), indent=2, ensure_ascii=False
            )
            + "\n"
        )
        yield path, old, new


def check(repo_root: Path) -> tuple[list[str], list[str]]:
    """Errors (claims, vocabulary, stale tables) and report-only warnings."""
    result = resolve(repo_root)
    errors = list(result.errors)
    errors += tabs.check(
        repo_root,
        {
            project: [i.label for i in matrix.interfaces.values()]
            for project, matrix in result.matrices.items()
        },
    )
    for page, lines, new in _rendered(repo_root, result, errors):
        if lines != new:
            diff = "\n".join(
                list(difflib.unified_diff(lines, new, lineterm="", n=0))[2:14]
            )
            rel = page.relative_to(repo_root)
            errors.append(
                f"{rel}: compatibility table is stale; run "
                f"`uv run docsnip compat --fix`\n{diff}"
            )
    for path, old, new in _artifacts(repo_root, result):
        if old != new:
            errors.append(
                f"{path.relative_to(repo_root)} is stale; run "
                "`uv run docsnip compat --fix`"
            )
    return errors, result.warnings


def fix(repo_root: Path) -> list[Path]:
    """Rewrite every embedded table and artifact; returns the files changed.

    Raises:
        ValueError: when the claims or vocabulary have errors, so a broken
            table is never written.
    """
    result = resolve(repo_root)
    errors = list(result.errors)
    changed: list[tuple[Path, list[str]]] = [
        (page, new)
        for page, lines, new in _rendered(repo_root, result, errors)
        if lines != new
    ]
    files = [(page, "\n".join(new)) for page, new in changed]
    files += [(p, new) for p, old, new in _artifacts(repo_root, result) if old != new]
    if errors:
        raise ValueError("\n".join(errors))
    for path, text in files:
        path.write_text(text)
    return [path for path, _ in files]


# --- the estate model ---------------------------------------------------------


def _listed(journeys: list[str]) -> str:
    shown = ", ".join(journeys[:3])
    return shown + (f", +{len(journeys) - 3} more" if len(journeys) > 3 else "")


def model_gaps(repo_root: Path) -> list[str]:
    """:func:`diagnostics` for every matrix, one line each. Report-only."""
    if not (repo_root / "architecture" / "dist" / "model.json").is_file():
        return []
    try:
        result = resolve(repo_root)
    except (OSError, ValueError):
        return []
    gaps: list[str] = []
    for project, matrix in sorted(result.matrices.items()):
        for d in diagnostics(result, matrix):
            kind = d["kind"]
            if kind == "unmodeled":
                gaps.append(
                    f"  - {project} {d['interface']}: CI-tested, but no model element"
                )
            elif kind == "missing-edge":
                journeys = list(d["journeys"])
                gaps.append(
                    f"  - {project} {d['interface']}: proves {_listed(journeys)} "
                    f"against {d['target']}, but {d['source']} has no "
                    "consumes/implements edge to it"
                )
            elif kind == "unmigrated":
                journeys = list(d["journeys"])
                gaps.append(
                    f"  - {project}: {len(journeys)} journey(s) with no asset or "
                    f"requirements ({_listed(journeys)})"
                )
            elif kind == "unverified-asset":
                gaps.append(
                    f"  - {project}: {matrix.spec} governs {d['asset']}, but no "
                    "journey on it is verified"
                )
            elif kind == "missing-asset-edge":
                journeys = list(d["journeys"])
                gaps.append(
                    f"  - {project} {d['interface']}: proves {_listed(journeys)} "
                    f"on {d['asset']}, but {d['source']} has no operatesOn edge"
                )
            elif kind == "unverified-asset-edge":
                gaps.append(
                    f"  - {project}: {d['source']} operatesOn {d['asset']}, but "
                    "no ready journey verifies the edge"
                )
    return gaps


def stale(repo_root: Path) -> list[Path]:
    """The committed compatibility artifacts ``compat --fix`` would rewrite."""
    try:
        result = resolve(repo_root)
    except (OSError, ValueError):
        return []
    return [path for path, old, new in _artifacts(repo_root, result) if old != new]
