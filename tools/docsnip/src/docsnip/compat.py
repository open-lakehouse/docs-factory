"""Compatibility matrices: what each engine or client can do, proven by CI.

``content/<project>/compatibility.yml`` declares a project's matrix: its
interfaces (the columns), its operations, the tables pages embed (rows of
operations), and evidence for cells no script here proves. Scripts claim cells
through ``[tool.docs-factory].claims`` (see :class:`docsnip.scriptmeta.Claim`).

A cell is ✓ or ✗ from a claim only when the claiming script's page is
``status: ready``, because only those scripts gate CI (content/conftest.py). So
a ✓ means a test that blocks merges runs the operation. ``fix`` renders each
table between its markers in the page that embeds it; ``check`` reports what's
inconsistent or stale. See docs/design/model-leverage.md §3.1.
"""

from __future__ import annotations

import dataclasses
import difflib
import json
import posixpath
import re
from collections.abc import Iterable
from pathlib import Path

import yaml

from . import shellregions
from .anchors import headings
from .frontmatter import iter_content_files, page_status
from .scriptmeta import Claim, ScriptMeta, discover, without_metadata
from .snippetcheck import iter_fences

FILE = "compatibility.yml"
OUTCOMES = ("fails", "missing")

_MATRIX_KEYS = {"spec", "interfaces", "operations", "tables", "evidence"}
_INTERFACE_KEYS = {"label", "pin", "package", "model"}
_TABLE_KEYS = {"columns", "rows"}
_ROW_KEYS = {"label", "ops"}
_EVIDENCE_KEYS = {"interfaces", "ops", "outcome", "why", "source", "verified", "note"}

_OPEN_RE = re.compile(r"^<!-- compat:(?P<table>[\w.-]+)\b.*-->\s*$")
_CLOSE = "<!-- /compat:{table} -->"
_OPEN = (
    "<!-- compat:{table} generated by `uv run docsnip compat --fix` from "
    "{source} and script claims; edit those, not this table -->"
)
_FRONTMATTER_RE = re.compile(r"^---\r?\n[\s\S]*?\r?\n---\r?\n?")


@dataclasses.dataclass(frozen=True)
class Interface:
    key: str
    label: str
    pin: str | None = None  # a release.yml pin; the header shows its major.minor
    package: str | None = None  # every claiming script pins one version of it
    model: str | None = None  # an estate-model element id


@dataclasses.dataclass(frozen=True)
class Row:
    label: str
    ops: tuple[str, ...]


@dataclasses.dataclass(frozen=True)
class Table:
    id: str
    columns: tuple[str, ...]
    rows: tuple[Row, ...]


@dataclasses.dataclass(frozen=True)
class Evidence:
    interfaces: tuple[str, ...]
    ops: tuple[str, ...]
    outcome: str
    why: str
    source: str
    verified: dict[str, str]
    note: str | None = None


@dataclasses.dataclass
class Matrix:
    project: str
    path: Path
    spec: str | None
    interfaces: dict[str, Interface]
    operations: dict[str, str]
    tables: dict[str, Table]
    evidence: list[Evidence]
    pins: dict[str, str]  # from content/<project>/release.yml


@dataclasses.dataclass(frozen=True)
class Proof:
    """A claim with what the matrix needs to render it."""

    script: str  # repo-relative POSIX path
    page: Path
    claim: Claim
    anchor: str | None
    ready: bool


@dataclasses.dataclass
class Result:
    matrices: dict[str, Matrix]
    proofs: dict[tuple[str, str, str], list[Proof]]  # (project, interface, op)
    errors: list[str]
    warnings: list[str]


# --- loading ------------------------------------------------------------------


def _strs(value: object) -> tuple[str, ...] | None:
    if isinstance(value, list) and all(isinstance(v, str) for v in value):
        return tuple(str(v) for v in value)
    return None


def _release_pins(project_dir: Path) -> dict[str, str]:
    path = project_dir / "release.yml"
    if not path.is_file():
        return {}
    raw = yaml.safe_load(path.read_text()) or {}
    pins = {k: str(v) for k, v in (raw.get("pins") or {}).items()}
    if raw.get("release"):
        pins["release"] = str(raw["release"])
    return pins


def _load_matrix(path: Path, model_ids: set[str], errors: list[str]) -> Matrix | None:
    try:
        raw = yaml.safe_load(path.read_text()) or {}
    except yaml.YAMLError as exc:
        errors.append(f"{path}: {exc}")
        return None
    where = str(path)
    if not isinstance(raw, dict):
        errors.append(f"{where}: must be a mapping")
        return None
    for key in sorted(set(raw) - _MATRIX_KEYS):
        errors.append(f"{where}: unknown key '{key}'")
    pins = _release_pins(path.parent)

    def known_model(value: object, at: str) -> None:
        if not isinstance(value, str):
            errors.append(f"{where}: {at} must be a model element id")
        elif model_ids and value not in model_ids:
            errors.append(f"{where}: {at} '{value}' is not in the estate model")

    spec = raw.get("spec")
    if spec is not None:
        known_model(spec, "spec")

    interfaces: dict[str, Interface] = {}
    for key, entry in (raw.get("interfaces") or {}).items():
        at = f"interfaces.{key}"
        if not isinstance(entry, dict) or not isinstance(entry.get("label"), str):
            errors.append(f"{where}: {at} needs a label")
            continue
        for extra in sorted(set(entry) - _INTERFACE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        if "pin" in entry and entry["pin"] not in pins:
            errors.append(f"{where}: {at}.pin '{entry['pin']}' is not in release.yml")
        if "model" in entry:
            known_model(entry["model"], f"{at}.model")
        interfaces[key] = Interface(
            key=key,
            label=entry["label"],
            pin=entry.get("pin"),
            package=entry.get("package"),
            model=entry.get("model"),
        )

    operations: dict[str, str] = {}
    for key, meaning in (raw.get("operations") or {}).items():
        if not isinstance(meaning, str):
            errors.append(f"{where}: operations.{key} must say what it means")
        operations[str(key)] = str(meaning)

    tables: dict[str, Table] = {}
    for tid, entry in (raw.get("tables") or {}).items():
        at = f"tables.{tid}"
        if not isinstance(entry, dict):
            errors.append(f"{where}: {at} must be a mapping")
            continue
        for extra in sorted(set(entry) - _TABLE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        columns = _strs(entry.get("columns")) or ()
        for col in columns:
            if col not in interfaces:
                errors.append(f"{where}: {at}: column '{col}' is not an interface")
        rows: list[Row] = []
        for i, row in enumerate(entry.get("rows") or []):
            ops = _strs(row.get("ops")) if isinstance(row, dict) else None
            if not ops or not isinstance(row.get("label"), str):
                errors.append(f"{where}: {at}.rows[{i}] needs a label and ops")
                continue
            for extra in sorted(set(row) - _ROW_KEYS):
                errors.append(f"{where}: {at}.rows[{i}]: unknown key '{extra}'")
            for op in ops:
                if op not in operations:
                    errors.append(
                        f"{where}: {at}.rows[{i}]: '{op}' is not an operation"
                    )
            rows.append(Row(label=row["label"], ops=ops))
        if not columns or not rows:
            errors.append(f"{where}: {at} needs columns and rows")
        tables[str(tid)] = Table(id=str(tid), columns=columns, rows=tuple(rows))

    evidence: list[Evidence] = []
    for i, entry in enumerate(raw.get("evidence") or []):
        at = f"evidence[{i}]"
        if not isinstance(entry, dict):
            errors.append(f"{where}: {at} must be a mapping")
            continue
        for extra in sorted(set(entry) - _EVIDENCE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        ifaces = _strs(entry.get("interfaces")) or ()
        ops = _strs(entry.get("ops")) or ()
        outcome = entry.get("outcome")
        if not ifaces or not ops:
            errors.append(f"{where}: {at} needs interfaces and ops")
        for iface in ifaces:
            if iface not in interfaces:
                errors.append(f"{where}: {at}: '{iface}' is not an interface")
        for op in ops:
            if op not in operations:
                errors.append(f"{where}: {at}: '{op}' is not an operation")
        if outcome not in OUTCOMES:
            errors.append(
                f"{where}: {at}: outcome must be one of {', '.join(OUTCOMES)}"
            )
        for key in ("why", "source"):
            if not isinstance(entry.get(key), str) or not entry[key]:
                errors.append(f"{where}: {at} needs a {key}")
        verified = entry.get("verified") or {}
        if not isinstance(verified, dict):
            errors.append(f"{where}: {at}: verified maps interfaces to versions")
            verified = {}
        evidence.append(
            Evidence(
                interfaces=ifaces,
                ops=ops,
                outcome=str(outcome),
                why=str(entry.get("why", "")),
                source=str(entry.get("source", "")),
                verified={str(k): str(v) for k, v in verified.items()},
                note=entry.get("note"),
            )
        )

    return Matrix(
        project=path.parent.name,
        path=path,
        spec=spec if isinstance(spec, str) else None,
        interfaces=interfaces,
        operations=operations,
        tables=tables,
        evidence=evidence,
        pins=pins,
    )


def _model_ids(repo_root: Path) -> set[str]:
    path = repo_root / "architecture" / "dist" / "model.json"
    if not path.is_file():
        return set()
    return set(json.loads(path.read_text()).get("elements", {}))


# --- pages and links ----------------------------------------------------------


def _page_route(page: Path, content_root: Path) -> str:
    """``unitycatalog/how-to/duckdb/index.md``: the path-derived identity that
    source-relative links between pages use (order prefixes stripped)."""
    parts = list(page.resolve().relative_to(content_root.resolve()).parts)
    if page.name in ("index.md", "index.mdx"):
        parts[-2] = re.sub(r"^\d+-", "", parts[-2])
    else:
        parts[-1] = re.sub(r"^\d+-", "", parts[-1])
    return "/".join(parts)


def _link(target: Path, anchor: str | None, embed: Path, content_root: Path) -> str:
    start = posixpath.dirname(_page_route(embed, content_root))
    rel = posixpath.relpath(_page_route(target, content_root), start)
    return f"{rel}#{anchor}" if anchor else rel


def _without_frontmatter(text: str) -> str:
    """The text with its frontmatter lines blanked, so line numbers still match."""
    m = _FRONTMATTER_RE.match(text)
    if not m:
        return text
    return "\n" * m.group(0).count("\n") + text[m.end() :]


def _heading_above(page: Path, line: int) -> str | None:
    found = [
        h for h in headings(_without_frontmatter(page.read_text())) if h.line < line
    ]
    return found[-1].id if found else None


# --- claims -------------------------------------------------------------------


def _project_of(path: Path, content_root: Path) -> str | None:
    try:
        return path.resolve().relative_to(content_root.resolve()).parts[0]
    except ValueError:
        return None


def _resolve(
    meta: ScriptMeta,
    claim: Claim,
    matrices: dict[str, Matrix],
    repo_root: Path,
    errors: list[str],
) -> tuple[str, Proof] | None:
    content_root = repo_root / "content"
    rel = meta.path.resolve().relative_to(repo_root.resolve()).as_posix()
    where = f"{rel}: claims.{claim.interface}: {claim.op}"
    project, _, iface = claim.interface.rpartition(":")
    project = project or _project_of(meta.path, content_root) or ""
    matrix = matrices.get(project)
    if matrix is None:
        errors.append(f"{where}: no content/{project}/{FILE}")
        return None
    if iface not in matrix.interfaces:
        errors.append(f"{where}: '{iface}' is not an interface in {matrix.path.name}")
        return None
    if claim.op not in matrix.operations:
        errors.append(
            f"{where}: '{claim.op}' is not an operation in {matrix.path.name}"
        )
        return None
    page = meta.owning_page()
    if page is None:
        errors.append(f"{where}: the script belongs to no page")
        return None

    page_ids = {h.id for h in headings(_without_frontmatter(page.read_text()))}
    anchor = claim.anchor
    if anchor is not None and anchor not in page_ids:
        errors.append(f"{where}: no heading '#{anchor}' on {page.name}")
        return None
    if claim.region is not None:
        shown = meta.verifies_path() or meta.path.resolve()
        if claim.region not in shellregions.regions(shown):
            errors.append(f"{where}: no region '{claim.region}' in {shown.name}")
            return None
        fences = [
            f
            for f in iter_fences(page)
            if (page.parent / f.file).resolve() == shown and f.region == claim.region
        ]
        if not fences:
            errors.append(f"{where}: {page.name} shows no region '{claim.region}'")
            return None
        if anchor is None:
            anchor = _heading_above(page, fences[0].line)
    code = without_metadata(meta.path.read_text())
    if isinstance(claim.fails, str) and claim.fails not in code:
        errors.append(f"{where}: the script doesn't assert '{claim.fails}'")
        return None

    proof = Proof(
        script=rel,
        page=page,
        claim=dataclasses.replace(claim, interface=iface),
        anchor=anchor,
        ready=page_status(page) == "ready",
    )
    return project, proof


def _source_problem(source: str, project_dir: Path) -> str | None:
    """Why an evidence ``source`` doesn't resolve, or None. A source is a URL or
    ``<bucket>/<slug>[#anchor]``, the page identity nav.yml uses."""
    if not source or re.match(r"^https?://", source):
        return None
    path, _, anchor = source.partition("#")
    bucket, _, slug = path.partition("/")
    pages = [
        page
        for page in sorted((project_dir / bucket).glob("*/index.md"))
        if re.sub(r"^\d+-", "", page.parent.name) == slug
    ]
    if not pages:
        return "no such page"
    if anchor and anchor not in {
        h.id for h in headings(_without_frontmatter(pages[0].read_text()))
    }:
        return f"no heading '#{anchor}' on it"
    return None


def _package_pins(meta: ScriptMeta) -> dict[str, str]:
    pins: dict[str, str] = {}
    for dep in meta.dependencies:
        m = re.match(r"^\s*([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?\s*==\s*([\w.]+)\s*$", dep)
        if m:
            pins[m.group(1).lower()] = m.group(2)
    return pins


def resolve(repo_root: Path) -> Result:
    content_root = repo_root / "content"
    errors: list[str] = []
    warnings: list[str] = []
    model_ids = _model_ids(repo_root)
    matrices: dict[str, Matrix] = {}
    for path in sorted(content_root.glob(f"*/{FILE}")):
        matrix = _load_matrix(path, model_ids, errors)
        if matrix is not None:
            matrices[matrix.project] = matrix

    for matrix in matrices.values():
        for ev in matrix.evidence:
            problem = _source_problem(ev.source, content_root / matrix.project)
            if problem:
                errors.append(f"{matrix.path}: evidence source {ev.source}: {problem}")

    proofs: dict[tuple[str, str, str], list[Proof]] = {}
    versions: dict[tuple[str, str], dict[str, list[str]]] = {}
    for meta in discover(content_root):
        for claim in meta.docs_factory.claims:
            resolved = _resolve(meta, claim, matrices, repo_root, errors)
            if resolved is None:
                continue
            project, proof = resolved
            iface = matrices[project].interfaces[proof.claim.interface]
            if iface.package:
                pin = _package_pins(meta).get(iface.package.lower())
                if pin:
                    seen = versions.setdefault((project, iface.key), {})
                    seen.setdefault(pin, [])
                    if proof.script not in seen[pin]:
                        seen[pin].append(proof.script)
            if not proof.ready:
                warnings.append(
                    f"{proof.script}: {proof.claim.interface} {proof.claim.op} "
                    f"renders once {proof.page.parent.name} is ready"
                )
                continue
            proofs.setdefault((project, iface.key, proof.claim.op), []).append(proof)

    for (project, iface), seen in sorted(versions.items()):
        if len(seen) > 1:
            listed = "; ".join(f"{v}: {', '.join(s)}" for v, s in sorted(seen.items()))
            errors.append(
                f"{project} {iface}: claiming scripts pin different "
                f"{matrices[project].interfaces[iface].package} versions ({listed})"
            )
        matrix = matrices[project]
        tested = next(iter(seen)) if len(seen) == 1 else None
        for ev in matrix.evidence:
            verified = ev.verified.get(iface)
            if tested and verified and verified != tested:
                warnings.append(
                    f"{matrix.path.name}: {iface} {', '.join(ev.ops)} was verified "
                    f"with {verified}, scripts now pin {tested}; re-verify"
                )

    for (project, iface, op), cell in proofs.items():
        cell.sort(key=lambda p: p.script)
        if len({p.claim.works for p in cell}) > 1:
            errors.append(
                f"{project} {iface} {op}: scripts disagree whether it works "
                f"({', '.join(p.script for p in cell)})"
            )
    for project, matrix in matrices.items():
        for ev in matrix.evidence:
            for iface in ev.interfaces:
                for op in ev.ops:
                    cell = proofs.get((project, iface, op))
                    if not cell:
                        continue
                    if cell[0].claim.works:
                        errors.append(
                            f"{matrix.path.name}: evidence says {iface} {op} "
                            f"{ev.outcome}, but {cell[0].script} proves it works"
                        )
                    else:
                        warnings.append(
                            f"{matrix.path.name}: evidence for {iface} {op} is "
                            f"redundant; {cell[0].script} asserts the failure"
                        )
    return Result(matrices=matrices, proofs=proofs, errors=errors, warnings=warnings)


# --- rendering ----------------------------------------------------------------


def _header(iface: Interface, matrix: Matrix) -> str:
    label = iface.label
    if iface.pin and iface.pin in matrix.pins:
        label += " " + ".".join(matrix.pins[iface.pin].split(".")[:2])
    return f"[{label}](model:{iface.model})" if iface.model else label


def _cell(
    result: Result,
    matrix: Matrix,
    row: Row,
    iface: str,
    embed: Path,
    content_root: Path,
    where: str,
    errors: list[str],
) -> str:
    states: list[str] = []
    links: list[str | None] = []
    notes: set[str] = set()
    for op in row.ops:
        cell = result.proofs.get((matrix.project, iface, op))
        evidence = [e for e in matrix.evidence if iface in e.interfaces and op in e.ops]
        if cell:
            first = cell[0]
            states.append("works" if first.claim.works else "fails")
            notes.update(p.claim.note for p in cell if p.claim.note)
            anchored = (
                first
                if first.claim.works
                else next((p for p in cell if p.anchor), None)
            )
            links.append(
                _link(anchored.page, anchored.anchor, embed, content_root)
                if anchored
                else None
            )
        elif evidence:
            states.append("fails")
            notes.update(e.note for e in evidence if e.note)
            links.append(None)
        else:
            states.append("unknown")
            links.append(None)
    kinds = set(states)
    if len(kinds) > 1:
        errors.append(
            f"{where}: row '{row.label}', {iface}: its operations differ "
            f"({', '.join(f'{o} {s}' for o, s in zip(row.ops, states, strict=True))}); "
            "split the row"
        )
        return "?"
    if len(notes) > 1:
        errors.append(f"{where}: row '{row.label}', {iface}: more than one note")
        return "?"
    kind = states[0]
    if kind == "unknown":
        return "—"
    symbol = "✓" if kind == "works" else "✗"
    link = next((link for link in links if link), None)
    text = f"[{symbol}]({link})" if link else symbol
    return f"{text} {notes.pop()}" if notes else text


def render(
    result: Result, matrix: Matrix, table: Table, embed: Path, content_root: Path
) -> tuple[list[str], list[str]]:
    """The table's Markdown lines for a page that embeds it, and any errors."""
    errors: list[str] = []
    where = f"{matrix.path.name} tables.{table.id}"
    ifaces = [matrix.interfaces[c] for c in table.columns if c in matrix.interfaces]
    lines = [
        "| Operation | " + " | ".join(_header(i, matrix) for i in ifaces) + " |",
        "| --- |" + " --- |" * len(ifaces),
    ]
    for row in table.rows:
        cells = [
            _cell(result, matrix, row, i.key, embed, content_root, where, errors)
            for i in ifaces
        ]
        lines.append(f"| {row.label} | " + " | ".join(cells) + " |")
    return lines, errors


# --- embedding: check and fix -------------------------------------------------


@dataclasses.dataclass
class _Embed:
    page: Path
    table: str
    start: int  # index of the opening marker line
    end: int  # index of the closing marker line


def _embeds(page: Path, lines: list[str], errors: list[str]) -> list[_Embed]:
    found: list[_Embed] = []
    i = 0
    while i < len(lines):
        m = _OPEN_RE.match(lines[i])
        if not m:
            i += 1
            continue
        table = m.group("table")
        close = _CLOSE.format(table=table)
        end = next(
            (j for j in range(i + 1, len(lines)) if lines[j].strip() == close), None
        )
        if end is None:
            errors.append(f"{page}: compat:{table} has no closing `{close}`")
            break
        found.append(_Embed(page=page, table=table, start=i, end=end))
        i = end + 1
    return found


def _rendered(
    repo_root: Path, result: Result, errors: list[str]
) -> Iterable[tuple[Path, list[str], list[str]]]:
    """Each page that embeds a table: its current lines and its rendered lines."""
    content_root = repo_root / "content"
    embedded: dict[tuple[str, str], list[Path]] = {}
    for page in iter_content_files(content_root):
        text = page.read_text()
        if "<!-- compat:" not in text:
            continue
        lines = text.split("\n")
        new = list(lines)
        project = _project_of(page, content_root) or ""
        matrix = result.matrices.get(project)
        # Replace from the bottom up so earlier indices stay valid.
        for embed in reversed(_embeds(page, lines, errors)):
            table = matrix.tables.get(embed.table) if matrix else None
            if matrix is None or table is None:
                errors.append(
                    f"{page}: compat:{embed.table} is not a table in "
                    f"content/{project}/{FILE}"
                )
                continue
            embedded.setdefault((project, embed.table), []).append(page)
            body, render_errors = render(result, matrix, table, page, content_root)
            errors.extend(render_errors)
            source = posixpath.relpath(
                f"{project}/{FILE}", posixpath.dirname(_page_route(page, content_root))
            )
            new[embed.start : embed.end + 1] = [
                _OPEN.format(table=embed.table, source=source),
                *body,
                _CLOSE.format(table=embed.table),
            ]
        yield page, lines, new
    for (project, tid), pages in sorted(embedded.items()):
        if len(pages) > 1:
            errors.append(
                f"{project} tables.{tid} is embedded more than once: "
                + ", ".join(str(p) for p in pages)
            )
    for project, matrix in sorted(result.matrices.items()):
        for tid in matrix.tables:
            if (project, tid) not in embedded:
                result.warnings.append(
                    f"{matrix.path.name}: tables.{tid} is on no page"
                )


def check(repo_root: Path) -> tuple[list[str], list[str]]:
    """Errors (claims, vocabulary, stale tables) and report-only warnings."""
    result = resolve(repo_root)
    errors = list(result.errors)
    for page, lines, new in _rendered(repo_root, result, errors):
        if lines != new:
            diff = "\n".join(
                list(difflib.unified_diff(lines, new, lineterm="", n=0))[2:14]
            )
            rel = page.relative_to(repo_root)
            errors.append(
                f"{rel}: compatibility table is stale; run "
                f"`uv run docsnip compat --fix`\n{diff}"
            )
    return errors, result.warnings


def fix(repo_root: Path) -> list[Path]:
    """Rewrite every embedded table; returns the pages changed.

    Raises:
        ValueError: when the claims or vocabulary have errors, so a broken
            table is never written.
    """
    result = resolve(repo_root)
    errors = list(result.errors)
    changed: list[tuple[Path, list[str]]] = [
        (page, new)
        for page, lines, new in _rendered(repo_root, result, errors)
        if lines != new
    ]
    if errors:
        raise ValueError("\n".join(errors))
    for page, new in changed:
        page.write_text("\n".join(new))
    return [page for page, _ in changed]


# --- the estate model ---------------------------------------------------------

_SPEC_EDGES = {"consumes", "implements"}


def model_gaps(repo_root: Path) -> list[str]:
    """Interfaces CI proves things about that the estate model doesn't connect.

    Report-only: a tested interface with no model element, or whose element has
    no ``consumes`` / ``implements`` edge to the matrix's ``spec``.
    """
    path = repo_root / "architecture" / "dist" / "model.json"
    if not path.is_file():
        return []
    try:
        result = resolve(repo_root)
    except (OSError, ValueError):
        return []
    edges: set[tuple[str, str]] = set()
    for rel in json.loads(path.read_text()).get("relations", {}).values():
        source, target = rel.get("source") or {}, rel.get("target") or {}
        if rel.get("kind") in _SPEC_EDGES:
            edges.add((str(source.get("model")), str(target.get("model"))))
    gaps: list[str] = []
    tested = {(project, iface) for project, iface, _ in result.proofs}
    for project, iface in sorted(tested):
        matrix = result.matrices[project]
        entry = matrix.interfaces[iface]
        if entry.model is None:
            gaps.append(f"  - {project} {iface}: CI-tested, but no model element")
        elif matrix.spec and (entry.model, matrix.spec) not in edges:
            gaps.append(
                f"  - {project} {iface}: CI-tested against {matrix.spec}, but "
                f"{entry.model} has no consumes/implements edge to it"
            )
    return gaps
