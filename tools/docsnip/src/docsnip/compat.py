@dataclasses.dataclass(frozen=True)
class Interface:
    key: str
    label: str
    pin: str | None = None  # a release.yml pin; the header shows its major.minor
    package: str | None = None  # every claiming script pins one version of it
    model: str | None = None  # an estate-model element id
    via: str | None = None  # the package the interface reaches tables through
    # What `model` integrates for its spec support (a Spark connector, a DuckDB
    # extension, a format library). A spec edge the model has itself wins, so an
    # integration is credited only with what the engine lacks.
    integrations: tuple[str, ...] = ()
    # An engine-level column: the language interfaces whose claims it shows,
    # best cell first. Scripts claim the language they show, never this.
    rollup: tuple[str, ...] = ()

    @property
    def speakers(self) -> tuple[str, ...]:
        """The elements whose spec edges count for this interface, model first."""
        return ((self.model,) if self.model else ()) + self.integrations


# participant role → requirement edge → element ids, all of which must hold
Requirements = dict[str, dict[str, tuple[str, ...]]]


@dataclasses.dataclass(frozen=True)
class Feature:
    """The spec feature a journey exercises, so tables can group by spec version."""

    spec: str  # an openSpecification model id
    name: str  # an obligation in architecture/journeys/obligations/<spec>.yml
    since: str | None = (
        None  # the spec version that added it: "v3", "reader 3 · writer 7"
    )


@dataclasses.dataclass(frozen=True)
class Obligation:
    """One thing a spec asks of the roles that take part in it."""

    spec: str
    name: str
    roles: tuple[str, ...]  # of the spec's client-side roles
    since: str | None = None


@dataclasses.dataclass(frozen=True)
class Obligations:
    """architecture/journeys/obligations/<spec>.yml."""

    spec: str
    roles: tuple[str, ...]  # the roles a client takes: reader, writer, client
    items: dict[str, Obligation]


@dataclasses.dataclass(frozen=True)
class Cover:
    """An obligation a journey exercises, in the role its client takes."""

    spec: str
    name: str
    role: str


@dataclasses.dataclass(frozen=True)
class Journey:
    id: str
    title: str  # the row label: what the reader sets out to do
    summary: str  # one sentence the review app shows under the title
    request: str | None = None  # uuid of the review-app request that asked for it
