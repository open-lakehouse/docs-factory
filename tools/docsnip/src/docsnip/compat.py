def _strs(value: object) -> tuple[str, ...] | None:
    if isinstance(value, list) and all(isinstance(v, str) for v in value):
        return tuple(str(v) for v in value)
    return None


def _release_pins(project_dir: Path) -> dict[str, str]:
    path = project_dir / "release.yml"
    if not path.is_file():
        return {}
    raw = yaml.safe_load(path.read_text()) or {}
    pins = {k: str(v) for k, v in (raw.get("pins") or {}).items()}
    if raw.get("release"):
        pins["release"] = str(raw["release"])
    return pins


def _check_element(
    model: Model, value: object, kinds: set[str], at: str, where: str, errors: list[str]
) -> bool:
    if not isinstance(value, str):
        errors.append(f"{where}: {at} must be a model element id")
        return False
    if not model.kinds:  # no exported model: nothing to check against
        return True
    kind = model.kinds.get(value)
    if kind is None:
        errors.append(f"{where}: {at} '{value}' is not in the estate model")
        return False
    if kind not in kinds:
        want = " or ".join(sorted(kinds))
        errors.append(f"{where}: {at} '{value}' is of kind {kind}; expected {want}")
        return False
    return True


def _load_requires(
    value: object, at: str, where: str, model: Model, errors: list[str]
) -> Requirements | None:
    if not isinstance(value, dict) or not value:
        errors.append(f"{where}: {at} maps participant roles to requirements")
        return None
    requires: Requirements = {}
    for role, edges in value.items():
        here = f"{at}.{role}"
        if not isinstance(role, str) or not _ROLE_RE.match(role):
            errors.append(f"{where}: {here}: a role is a lowercase name")
            continue
        if not isinstance(edges, dict) or not edges:
            errors.append(f"{where}: {here} maps consumes/implements/realizes to ids")
            continue
        parsed: dict[str, tuple[str, ...]] = {}
        for edge, ids in edges.items():
            if not isinstance(edge, str) or edge not in _REQUIRE_EDGES:
                errors.append(f"{where}: {here}: unknown requirement '{edge}'")
                continue
            names = _strs(ids)
            if not names:
                errors.append(f"{where}: {here}.{edge} must be a list of element ids")
                continue
            for name in names:
                _check_element(
                    model, name, _REQUIRE_EDGES[edge], f"{here}.{edge}", where, errors
                )
            parsed[edge] = names
        requires[role] = parsed
    return requires


def _merged(base: Requirements, extra: Requirements) -> Requirements:
    """``base`` with ``extra``'s ids added, role by role and edge by edge."""
    merged = {role: dict(edges) for role, edges in base.items()}
    for role, edges in extra.items():
        mine = merged.setdefault(role, {})
        for edge, ids in edges.items():
            have = mine.get(edge, ())
            mine[edge] = have + tuple(i for i in ids if i not in have)
    return merged


def _load_yaml(path: Path, errors: list[str]) -> object:
    try:
        return yaml.safe_load(path.read_text())
    except yaml.YAMLError as exc:
        errors.append(f"{path}: {exc}")
        return None


def _mapping(raw: object, where: str, errors: list[str]) -> dict:
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        errors.append(f"{where}: must be a mapping")
        return {}
    return raw


def _load_paths(
    raw: dict, where: str, model: Model, errors: list[str]
) -> dict[str, Requirements]:
    paths: dict[str, Requirements] = {}
    for name, entry in raw.items():
        at = str(name)
        if not isinstance(entry, dict) or "roles" not in entry:
            errors.append(f"{where}: {at} needs roles")
            continue
        for extra in sorted(set(entry) - _PATH_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        roles = _load_requires(entry["roles"], f"{at}.roles", where, model, errors)
        if roles is not None:
            paths[at] = roles
    return paths


def _load_interfaces(
    raw: dict, where: str, model: Model, errors: list[str]
) -> dict[str, Interface]:
    def known_model(value: object, at: str) -> None:
        if not isinstance(value, str):
            errors.append(f"{where}: {at} must be a model element id")
        elif model.kinds and value not in model.kinds:
            errors.append(f"{where}: {at} '{value}' is not in the estate model")

    interfaces: dict[str, Interface] = {}
    for key, entry in raw.items():
        at = str(key)
        if not isinstance(entry, dict) or not isinstance(entry.get("label"), str):
            errors.append(f"{where}: {at} needs a label")
            continue
        for extra in sorted(set(entry) - _INTERFACE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        if "model" in entry:
            known_model(entry["model"], f"{at}.model")
        integrations = entry.get("integrations") or []
        if not isinstance(integrations, list):
            errors.append(f"{where}: {at}.integrations must be a list of model ids")
            integrations = []
        for i, integration in enumerate(integrations):
            known_model(integration, f"{at}.integrations[{i}]")
            edge = ("integrates", entry.get("model"), integration)
            if model.kinds and edge not in model.edges:
                errors.append(
                    f"{where}: {at}.integrations[{i}]: {entry.get('model')!r} "
                    f"doesn't integrate '{integration}' in the estate model"
                )
        interfaces[at] = Interface(
            key=at,
            label=entry["label"],
            pin=entry.get("pin"),
            package=entry.get("package"),
            model=entry.get("model"),
            via=entry.get("via"),
            integrations=tuple(str(c) for c in integrations),
            rollup=tuple(str(m) for m in entry.get("rollup") or ()),
        )
    for iface in interfaces.values():
        for member in iface.rollup:
            other = interfaces.get(member)
            if other is None:
                errors.append(
                    f"{where}: {iface.key}.rollup: '{member}' is not an interface"
                )
            elif other.rollup:
                errors.append(
                    f"{where}: {iface.key}.rollup: '{member}' is a rollup itself"
                )
            elif other.model != iface.model:
                errors.append(
                    f"{where}: {iface.key}.rollup: '{member}' is bound to "
                    f"{other.model}, not {iface.model}"
                )
    return interfaces


def _load_obligations(
    raw: dict, where: str, model: Model, errors: list[str]
) -> Obligations | None:
    for extra in sorted(set(raw) - _OBLIGATIONS_KEYS):
        errors.append(f"{where}: unknown key '{extra}'")
    spec = raw.get("spec")
    if not _check_element(model, spec, {"openSpecification"}, "spec", where, errors):
        return None
    roles = _strs(raw.get("roles"))
    if not roles:
        errors.append(f"{where}: roles lists the roles a client takes")
        return None
    if not isinstance(raw.get("source"), str):
        errors.append(f"{where}: needs a source")
    items: dict[str, Obligation] = {}
    for name, entry in _mapping(raw.get("obligations"), where, errors).items():
        at = f"obligations.{name}"
        if not isinstance(entry, dict):
            errors.append(f"{where}: {at} must be a mapping")
            continue
        for extra in sorted(set(entry) - _OBLIGATION_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        own = _strs(entry["roles"]) if "roles" in entry else roles
        for role in set(own or ()) - set(roles):
            errors.append(f"{where}: {at}: role '{role}' is not one of {list(roles)}")
        since = entry.get("since")
        if since is not None and not isinstance(since, str):
            errors.append(f"{where}: {at}.since must be a string")
            since = None
        items[str(name)] = Obligation(
            spec=str(spec), name=str(name), roles=tuple(own or ()), since=since
        )
    return Obligations(spec=str(spec), roles=roles, items=items)


def _load_covers(
    value: object,
    at: str,
    where: str,
    obligations: dict[str, Obligations],
    errors: list[str],
) -> tuple[Cover, ...]:
    """``<spec>:<name>[:<role>]`` entries; the role may be left out only where
    the obligation binds one role."""
    entries = _strs(value)
    if entries is None:
        errors.append(f"{where}: {at} lists <spec>:<obligation>[:<role>] entries")
        return ()
    covers: list[Cover] = []
    for entry in entries:
        spec, _, rest = entry.partition(":")
        name, _, role = rest.partition(":")
        known = obligations.get(spec)
        if known is None:
            errors.append(f"{where}: {at}: '{spec}' has no obligations file")
            continue
        obligation = known.items.get(name)
        if obligation is None:
            errors.append(f"{where}: {at}: '{name}' is not a {spec} obligation")
            continue
        if not role:
            if len(obligation.roles) != 1:
                errors.append(
                    f"{where}: {at}: {spec}:{name} binds {', '.join(obligation.roles)}; "
                    "name the role the journey's client takes"
                )
                continue
            role = obligation.roles[0]
        elif role not in obligation.roles:
            errors.append(f"{where}: {at}: {spec}:{name} doesn't bind the {role} role")
            continue
        covers.append(Cover(spec=spec, name=name, role=role))
    return tuple(dict.fromkeys(covers))


def _load_journeys(
    raw: dict,
    where: str,
    errors: list[str],
    model: Model,
    paths: dict[str, Requirements],
    obligations: dict[str, Obligations],
) -> dict[str, Journey]:
    journeys: dict[str, Journey] = {}
    for key, entry in raw.items():
        at = str(key)
        if not isinstance(entry, dict) or not all(
            isinstance(entry.get(k), str) for k in ("title", "summary")
        ):
            errors.append(f"{where}: {at} needs a title and a summary")
            continue
        for extra in sorted(set(entry) - _JOURNEY_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        request = entry.get("request")
        if request is not None and not _UUID_RE.match(str(request)):
            errors.append(f"{where}: {at}.request must be a request uuid")
        path = entry.get("path")
        if path is None:
            errors.append(f"{where}: {at} needs a path")
        elif path not in paths:
            errors.append(f"{where}: {at}.path '{path}' is not in paths.yml")
        asset = entry.get("asset")
        if asset is None:
            errors.append(f"{where}: {at} needs an asset")
        elif not _check_element(model, asset, {"asset"}, f"{at}.asset", where, errors):
            asset = None
        roles = (
            _load_requires(entry["roles"], f"{at}.roles", where, model, errors)
            if "roles" in entry
            else None
        )
        covers = (
            _load_covers(entry["covers"], f"{at}.covers", where, obligations, errors)
            if "covers" in entry
            else ()
        )
        first = covers[0] if covers else None
        feature = (
            Feature(
                spec=first.spec,
                name=first.name,
                since=obligations[first.spec].items[first.name].since,
            )
            if first
            else None
        )
        journeys[at] = Journey(
            id=at,
            title=entry["title"],
            summary=entry["summary"],
            request=str(request) if request is not None else None,
            path=str(path) if path in paths else None,
            asset=asset if isinstance(asset, str) else None,
            requires=_merged(paths.get(str(path), {}), roles or {}),
            covers=covers,
            feature=feature,
        )
    return journeys


def _load_fact(
    entry: dict,
    at: str,
    where: str,
    model: Model,
    obligations: dict[str, Obligations],
    errors: list[str],
) -> Fact | None:
    for extra in sorted(set(entry) - _FACT_KEYS):
        errors.append(f"{where}: {at}: unknown key '{extra}'")
    implementation = entry.get("implementation")
    if not _check_element(
        model, implementation, {"implementation"}, f"{at}.implementation", where, errors
    ):
        return None
    named: list[tuple[str, str]] = []
    for ref in _strs(entry.get("obligations")) or ():
        spec, _, name = ref.partition(":")
        if name not in (obligations.get(spec) or Obligations(spec, (), {})).items:
            errors.append(f"{where}: {at}: '{ref}' is not an obligation")
            continue
        named.append((spec, name))
    if not named:
        errors.append(f"{where}: {at} needs obligations (<spec>:<obligation>)")
    outcome = entry.get("outcome")
    if outcome not in ("fails", "missing"):
        errors.append(f"{where}: {at}: a server fact's outcome is fails or missing")
    for key in ("why", "source"):
        if not isinstance(entry.get(key), str) or not entry[key]:
            errors.append(f"{where}: {at} needs a {key}")
    return Fact(
        implementation=str(implementation),
        obligations=tuple(named),
        outcome=str(outcome),
        why=str(entry.get("why", "")),
        source=str(entry.get("source", "")),
    )


def _load_evidence(
    raw: object,
    where: str,
    errors: list[str],
    interfaces: dict[str, Interface],
    journeys: dict[str, Journey],
    model: Model,
    obligations: dict[str, Obligations],
) -> tuple[list[Evidence], list[Fact]]:
    """Cells no script proves, and facts about one implementation (an entry
    with `implementation` and `obligations` instead of interfaces and journeys)."""
    if raw is None:
        return [], []
    if not isinstance(raw, list):
        errors.append(f"{where}: must be a list")
        return [], []
    entries: list[Any] = raw
    evidence: list[Evidence] = []
    facts: list[Fact] = []
    for i, entry in enumerate(entries):
        at = f"[{i}]"
        if not isinstance(entry, dict):
            errors.append(f"{where}: {at} must be a mapping")
            continue
        if "implementation" in entry:
            fact = _load_fact(entry, at, where, model, obligations, errors)
            if fact is not None:
                facts.append(fact)
            continue
        for extra in sorted(set(entry) - _EVIDENCE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        ifaces = _strs(entry.get("interfaces")) or ()
        names = _strs(entry.get("journeys")) or ()
        outcome = entry.get("outcome")
        if not ifaces or not names:
            errors.append(f"{where}: {at} needs interfaces and journeys")
        for iface in ifaces:
            if iface not in interfaces:
                errors.append(f"{where}: {at}: '{iface}' is not an interface")
        for name in names:
            if name not in journeys:
                errors.append(f"{where}: {at}: '{name}' is not a journey")
        if outcome not in OUTCOMES:
            errors.append(
                f"{where}: {at}: outcome must be one of {', '.join(OUTCOMES)}"
            )
        for key in ("why", "source"):
            if not isinstance(entry.get(key), str) or not entry[key]:
                errors.append(f"{where}: {at} needs a {key}")
        maps: dict[str, dict[str, str]] = {}
        for key in ("verified", "api"):
            value = entry.get(key) or {}
            if not isinstance(value, dict):
                errors.append(f"{where}: {at}: {key} maps interfaces to text")
                value = {}
            for iface in value:
                if iface not in ifaces:
                    errors.append(f"{where}: {at}: {key}.{iface} isn't in interfaces")
            maps[key] = {str(k): str(v) for k, v in value.items()}
        evidence.append(
            Evidence(
                interfaces=ifaces,
                journeys=names,
                outcome=str(outcome),
                why=str(entry.get("why", "")),
                source=str(entry.get("source", "")),
                verified=maps["verified"],
                api=maps["api"],
                note=entry.get("note"),
            )
        )
    return evidence, facts


def load_catalog(repo_root: Path, model: Model, errors: list[str]) -> Catalog:
    """The estate-wide journey catalog; empty where a file doesn't exist."""
    root = repo_root / CATALOG

    def read(name: str) -> tuple[object, str]:
        path = root / name
        return (_load_yaml(path, errors) if path.is_file() else None), str(path)

    raw, where = read("paths.yml")
    paths = _load_paths(_mapping(raw, where, errors), where, model, errors)
    raw, where = read("interfaces.yml")
    interfaces = _load_interfaces(_mapping(raw, where, errors), where, model, errors)

    obligations: dict[str, Obligations] = {}
    for path in sorted((root / "obligations").glob("*.yml")):
        where = str(path)
        found = _load_obligations(
            _mapping(_load_yaml(path, errors), where, errors), where, model, errors
        )
        if found is None:
            continue
        if path.stem != found.spec:
            errors.append(f"{where}: name the file after its spec ({found.spec}.yml)")
        obligations[found.spec] = found

    journeys: dict[str, Journey] = {}
    homes: dict[str, Path] = {}
    for path in sorted((root / "journeys").glob("*.yml")):
        where = str(path)
        raw = _mapping(_load_yaml(path, errors), where, errors)
        loaded = _load_journeys(raw, where, errors, model, paths, obligations)
        for jid, journey in loaded.items():
            if jid in journeys:
                errors.append(f"{where}: {jid} is already a journey in {homes[jid]}")
                continue
            journeys[jid], homes[jid] = journey, path

    raw, where = read("evidence.yml")
    evidence, facts = _load_evidence(
        raw, where, errors, interfaces, journeys, model, obligations
    )

    raw, where = read("aliases.yml")
    aliases: dict[str, str] = {}
    for old, new in _mapping(raw, where, errors).items():
        if old in journeys:
            errors.append(f"{where}: {old} is still a journey")
        elif new not in journeys:
            errors.append(f"{where}: {old} → '{new}', which is not a journey")
        else:
            aliases[str(old)] = str(new)
    return Catalog(
        paths=paths,
        interfaces=interfaces,
        journeys=journeys,
        evidence=evidence,
        aliases=aliases,
        obligations=obligations,
        facts=facts,
    )


def _load_matrix(
    path: Path, catalog: Catalog, model: Model, errors: list[str]
) -> Matrix | None:
    raw = _load_yaml(path, errors)
    if raw is None:
        return None
    where = str(path)
    if not isinstance(raw, dict):
        errors.append(f"{where}: must be a mapping")
        return None
    for key in sorted(set(raw) - _MATRIX_KEYS):
        errors.append(f"{where}: unknown key '{key}'")
    pins = _release_pins(path.parent)

    spec = raw.get("spec")
    if spec is not None and not isinstance(spec, str):
        errors.append(f"{where}: spec must be a model element id")
    elif spec is not None and model.kinds and spec not in model.kinds:
        errors.append(f"{where}: spec '{spec}' is not in the estate model")

    keys = _strs(raw.get("interfaces"))
    if keys is None:
        errors.append(f"{where}: interfaces lists interface keys, in tab order")
        keys = ()
    interfaces: dict[str, Interface] = {}
    for key in keys:
        iface = catalog.interfaces.get(key)
        if iface is None:
            errors.append(
                f"{where}: interface '{key}' is not in {CATALOG}/interfaces.yml"
            )
            continue
        if iface.pin and iface.pin not in pins:
            errors.append(f"{where}: {key}.pin '{iface.pin}' is not in release.yml")
        interfaces[key] = iface

    tables: dict[str, Table] = {}
    journeys: dict[str, Journey] = {}
    for tid, entry in _mapping(raw.get("tables"), f"{where}: tables", errors).items():
        at = f"tables.{tid}"
        if not isinstance(entry, dict):
            errors.append(f"{where}: {at} must be a mapping")
            continue
        for extra in sorted(set(entry) - _TABLE_KEYS):
            errors.append(f"{where}: {at}: unknown key '{extra}'")
        columns = _strs(entry.get("columns")) or ()
        for col in columns:
            if col not in interfaces:
                errors.append(f"{where}: {at}: column '{col}' is not an interface")
        rows = _strs(entry.get("rows")) or ()
        if "select" in entry:
            if rows:
                errors.append(f"{where}: {at} lists rows or selects them, not both")
            rows = _selected(entry["select"], f"{where}: {at}.select", catalog, errors)
        for row in rows:
            if row in catalog.journeys:
                journeys.setdefault(row, catalog.journeys[row])
            elif row in catalog.aliases:
                errors.append(
                    f"{where}: {at}: row '{row}' is now '{catalog.aliases[row]}'"
                )
            else:
                errors.append(f"{where}: {at}: row '{row}' is not a journey")
        if not columns or not rows:
            errors.append(f"{where}: {at} needs columns and rows of journey ids")
        tables[str(tid)] = Table(
            id=str(tid),
            title=str(entry.get("title") or tid),
            columns=columns,
            rows=tuple(r for r in rows if r in catalog.journeys),
            documented=entry.get("documented") is True,
        )

    providers: dict[str, str] = {}
    for role, impl in _mapping(
        raw.get("providers"), f"{where}: providers", errors
    ).items():
        if _check_element(
            model, impl, {"implementation"}, f"providers.{role}", where, errors
        ):
            providers[str(role)] = str(impl)

    evidence = [
        e
        for e in catalog.evidence
        if set(e.interfaces) & set(interfaces) and set(e.journeys) & set(journeys)
    ]
    evidence += _blocked(catalog, model, providers, interfaces, journeys)
    return Matrix(
        project=path.parent.name,
        path=path,
        spec=spec if isinstance(spec, str) else None,
        interfaces=interfaces,
        journeys=journeys,
        tables=tables,
        evidence=evidence,
        pins=pins,
        providers=providers,
    )


def _selected(
    value: object, where: str, catalog: Catalog, errors: list[str]
) -> tuple[str, ...]:
    """The catalog's journeys a ``select:`` matches, in catalog order: every
    key given must match (``asset`` a model id, ``paths`` any of the listed)."""
    if not isinstance(value, dict) or not value:
        errors.append(f"{where} maps asset and paths to what rows must match")
        return ()
    for extra in sorted(set(value) - _SELECT_KEYS):
        errors.append(f"{where}: unknown key '{extra}'")
    asset = value.get("asset")
    paths = _strs(value.get("paths")) if "paths" in value else None
    if "paths" in value and not paths:
        errors.append(f"{where}.paths must be a list of paths.yml names")
    for path in paths or ():
        if path not in catalog.paths:
            errors.append(f"{where}.paths: '{path}' is not in paths.yml")
    rows = tuple(
        j.id
        for j in catalog.journeys.values()
        if (asset is None or j.asset == asset) and (paths is None or j.path in paths)
    )
    if not rows:
        errors.append(f"{where} matches no journey")
    return rows


def _reaches(model: Model, iface: Interface) -> set[str]:
    """The open specifications the interface's model or integrations implement
    or consume."""
    return {
        target
        for kind, source, target in model.edges
        if source in iface.speakers
        and kind in _SPEC_EDGES
        and model.kinds.get(target) == "openSpecification"
    }


def _blocked(
    catalog: Catalog,
    model: Model,
    providers: dict[str, str],
    interfaces: dict[str, Interface],
    journeys: dict[str, Journey],
) -> list[Evidence]:
    """A provider's facts as evidence: a journey that covers an obligation its
    provider doesn't serve is blocked for every interface reaching that spec.

    The journey needs the obligation from the provider when the role the
    provider plays must implement the obligation's spec."""
    found: list[Evidence] = []
    for fact in catalog.facts:
        roles = [r for r, impl in providers.items() if impl == fact.implementation]
        blocked: list[str] = []
        ifaces: set[str] = set()
        for spec, name in fact.obligations:
            for journey in journeys.values():
                needs = any(
                    spec in journey.requires.get(role, {}).get("implements", ())
                    for role in roles
                )
                covers = any(c.spec == spec and c.name == name for c in journey.covers)
                if needs and covers and journey.id not in blocked:
                    blocked.append(journey.id)
            ifaces |= {k for k, i in interfaces.items() if spec in _reaches(model, i)}
        if blocked and ifaces:
            found.append(
                Evidence(
                    interfaces=tuple(k for k in interfaces if k in ifaces),
                    journeys=tuple(blocked),
                    outcome=fact.outcome,
                    why=fact.why,
                    source=fact.source,
                    verified={},
                    api={},
                    implementation=fact.implementation,
                )
            )
    return found


def load_model(repo_root: Path) -> Model:
    """The exported estate model, or an empty one when it hasn't been exported."""
    path = repo_root / "architecture" / "dist" / "model.json"
    if not path.is_file():
        return Model(kinds={}, titles={}, edges=set())
    data = json.loads(path.read_text())
    elements = data.get("elements") or {}
    edges = {
        (
            str(rel.get("kind")),
            str((rel.get("source") or {}).get("model")),
            str((rel.get("target") or {}).get("model")),
        )
        for rel in (data.get("relations") or {}).values()
    }
    return Model(
        kinds={k: str(v.get("kind")) for k, v in elements.items()},
        titles={k: str(v.get("title") or k) for k, v in elements.items()},
        edges=edges,
    )


# --- pages and links ----------------------------------------------------------


def _page_route(page: Path, content_root: Path) -> str:
    """``unitycatalog/how-to/duckdb/index.md``: the path-derived identity that
    source-relative links between pages use (order prefixes stripped)."""
    parts = list(page.resolve().relative_to(content_root.resolve()).parts)
    if page.name in ("index.md", "index.mdx"):
        parts[-2] = re.sub(r"^\d+-", "", parts[-2])
    else:
        parts[-1] = re.sub(r"^\d+-", "", parts[-1])
    return "/".join(parts)


def _link(target: Path, anchor: str | None, embed: Path, content_root: Path) -> str:
    start = posixpath.dirname(_page_route(embed, content_root))
    rel = posixpath.relpath(_page_route(target, content_root), start)
    return f"{rel}#{anchor}" if anchor else rel


def _without_frontmatter(text: str) -> str:
    """The text with its frontmatter lines blanked, so line numbers still match."""
    m = _FRONTMATTER_RE.match(text)
    if not m:
        return text
    return "\n" * m.group(0).count("\n") + text[m.end() :]


def _section_above(page: Path, line: int) -> Heading | None:
    found = [
        h for h in headings(_without_frontmatter(page.read_text())) if h.line < line
    ]
    return found[-1] if found else None


def _heading_above(page: Path, line: int) -> str | None:
    found = _section_above(page, line)
    return found.id if found else None


# --- claims -------------------------------------------------------------------


def _project_of(path: Path, content_root: Path) -> str | None:
    try:
        return path.resolve().relative_to(content_root.resolve()).parts[0]
    except ValueError:
        return None


# `group::artifact:version` (scala-cli) or `group:artifact_<scala>:version`.
_MAVEN_RE = re.compile(
    r"^[\w.-]+::?(?P<artifact>[\w.-]+?)(?:_2\.1[0-9])?:(?P<version>[\w.-]+)$"
)


def _package_pins(meta: ScriptMeta) -> dict[str, str]:
    """Package → pinned version; a Maven coordinate's package is its artifact, and
    a Rust script's `cargo add` argument reads `<crate>@<version>`."""
    pins: dict[str, str] = {}
    for dep in meta.dependencies:
        m = re.match(r"^\s*([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?\s*==\s*([\w.]+)\s*$", dep)
        if m:
            pins[m.group(1).lower()] = m.group(2)
        elif m := _MAVEN_RE.match(dep.strip()):
            pins[m.group("artifact").lower()] = m.group("version")
        elif m := re.match(r"^([\w-]+)@([\w.]+)(?:\s|$)", dep.strip()):
            pins[m.group(1).lower()] = m.group(2)
    return pins


# Region markers in a `//`-comment language (Scala, Java, Rust).
_SLASH_REGION_RE = re.compile(
    r"^[ \t]*//[ \t]*--8<-- \[start:([\w-]+)\][^\n]*\n(.*?)"
    r"^[ \t]*//[ \t]*--8<-- \[end:\1\]",
    re.S | re.M,
)


def _regions(path: Path) -> dict[str, str]:
    if path.suffix == ".sql":
        return sqlregions.regions(path)
    if path.suffix in (".sc", ".scala", ".java", ".rs"):
        return dict(_SLASH_REGION_RE.findall(path.read_text()))
    return shellregions.regions(path)


def _resolve(
    meta: ScriptMeta,
    claim: Claim,
    catalog: Catalog,
    matrices: dict[str, Matrix],
    repo_root: Path,
    errors: list[str],
    warnings: list[str],
) -> tuple[list[tuple[str, str]], Proof] | None:
    """The claim's proof, and each (project, interface) whose cell it fills:
    the claimed interface and every rollup of it, where a project lists that
    interface and shows the journey."""
    content_root = repo_root / "content"
    rel = meta.path.resolve().relative_to(repo_root.resolve()).as_posix()
    where = f"{rel}: claims.{claim.interface}: {claim.journey}"
    own = _project_of(meta.path, content_root) or ""
    iface, journey = claim.interface, claim.journey
    if ":" in iface:
        errors.append(
            f"{where}: interfaces are estate-wide; claim "
            f"'{iface.rpartition(':')[2]}' without a project"
        )
        return None
    if iface not in catalog.interfaces:
        errors.append(f"{where}: '{iface}' is not an interface in {CATALOG}")
        return None
    if catalog.interfaces[iface].rollup:
        members = " or ".join(catalog.interfaces[iface].rollup)
        errors.append(f"{where}: claim the interface the page shows ({members})")
        return None
    if journey in catalog.aliases:
        journey = catalog.aliases[journey]
        warnings.append(f"{where}: renamed to '{journey}'")
    if journey not in catalog.journeys:
        errors.append(f"{where}: '{journey}' is not a journey in {CATALOG}")
        return None
    keys = [iface] + [k for k, i in catalog.interfaces.items() if iface in i.rollup]
    projects = [
        (project, key)
        for project, matrix in sorted(matrices.items())
        for key in keys
        if key in matrix.interfaces and journey in matrix.journeys
    ]
    if not projects:
        errors.append(
            f"{where}: no project lists '{iface}' and shows '{journey}' on a table"
        )
        return None
    page = meta.owning_page()
    if page is None:
        errors.append(f"{where}: the script belongs to no page")
        return None

    page_ids = {h.id for h in headings(_without_frontmatter(page.read_text()))}
    anchor = claim.anchor
    if anchor is not None and anchor not in page_ids:
        errors.append(f"{where}: no heading '#{anchor}' on {page.name}")
        return None
    if claim.region is not None:
        shown = meta.verifies_path() or meta.path.resolve()
        if claim.region not in _regions(shown):
            errors.append(f"{where}: no region '{claim.region}' in {shown.name}")
            return None
        fences = [
            f
            for f in iter_fences(page)
            if (page.parent / f.file).resolve() == shown and f.region == claim.region
        ]
        if not fences:
            errors.append(f"{where}: {page.name} shows no region '{claim.region}'")
            return None
        if anchor is None:
            anchor = _heading_above(page, fences[0].line)
    code = without_metadata(meta.path.read_text())
    if isinstance(claim.fails, str) and claim.fails not in code:
        errors.append(f"{where}: the script doesn't assert '{claim.fails}'")
        return None

    package = catalog.interfaces[iface].package
    via = catalog.interfaces[iface].via
    proof = Proof(
        script=rel,
        project=own,
        page=page,
        claim=dataclasses.replace(claim, interface=iface, journey=journey),
        anchor=anchor,
        ready=page_status(page) == "ready",
        version=_package_pins(meta).get(package.lower()) if package else None,
        via_version=_package_pins(meta).get(via.lower()) if via else None,
    )
    return projects, proof


def _source_page(source: str, content_root: Path) -> tuple[Path | None, str | None]:
    """The page of a ``<project>:<bucket>/<slug>[#anchor]`` source, the page
    identity nav.yml uses, and why it doesn't resolve (None when it does).
    A URL resolves to no page and no problem."""
    if not source or re.match(r"^https?://", source):
        return None, None
    path, _, anchor = source.partition("#")
    project, _, path = path.rpartition(":")
    if not project:
        return None, "names no project (`<project>:<bucket>/<slug>`)"
    project_dir = content_root / project
    bucket, _, slug = path.partition("/")
    pages = [
        page
        for page in sorted((project_dir / bucket).glob("*/index.md"))
        if re.sub(r"^\d+-", "", page.parent.name) == slug
    ]
    if not pages:
        return None, "no such page"
    if anchor and anchor not in {
        h.id for h in headings(_without_frontmatter(pages[0].read_text()))
    }:
        return pages[0], f"no heading '#{anchor}' on it"
    return pages[0], None


def resolve(repo_root: Path) -> Result:
    content_root = repo_root / "content"
    errors: list[str] = []
    warnings: list[str] = []
    model = load_model(repo_root)
    catalog = load_catalog(repo_root, model, errors)
    matrices: dict[str, Matrix] = {}
    for path in sorted(content_root.glob(f"*/{FILE}")):
        matrix = _load_matrix(path, catalog, model, errors)
        if matrix is not None:
            matrices[matrix.project] = matrix

    tabled = {jid for matrix in matrices.values() for jid in matrix.journeys}
    for jid in catalog.journeys:
        if jid not in tabled:
            errors.append(f"{CATALOG}: {jid} is on no project's table")
    blocking = {
        e.implementation
        for m in matrices.values()
        for e in m.evidence
        if e.implementation
    }
    for fact in catalog.facts:
        if fact.implementation not in blocking:
            errors.append(
                f"{CATALOG}/evidence.yml: the facts about {fact.implementation} block "
                "no journey: no project's `providers` binds it, or no journey there "
                "covers the obligations"
            )
    for ev in [*catalog.evidence, *catalog.facts]:
        _, problem = _source_page(ev.source, content_root)
        if problem:
            errors.append(f"{CATALOG}/evidence.yml: source {ev.source}: {problem}")

    proofs: dict[tuple[str, str, str], list[Proof]] = {}
    # (script project, matrix project, interface) → version → scripts. A UC
    # script claiming a Delta cell pins UC's companions, not Delta's.
    versions: dict[tuple[str, str, str], dict[str, list[str]]] = {}
    for meta in discover(content_root):
        for claim in meta.docs_factory.claims:
            resolved = _resolve(
                meta, claim, catalog, matrices, repo_root, errors, warnings
            )
            if resolved is None:
                continue
            projects, proof = resolved
            iface = proof.claim.interface
            if not proof.ready:
                warnings.append(
                    f"{proof.script}: {iface} {proof.claim.journey} "
                    f"renders once {proof.page.parent.name} is ready"
                )
            for project, iface in projects:
                if proof.version:
                    seen = versions.setdefault((proof.project, project, iface), {})
                    seen.setdefault(proof.version, [])
                    if proof.script not in seen[proof.version]:
                        seen[proof.version].append(proof.script)
                key = (project, iface, proof.claim.journey)
                proofs.setdefault(key, []).append(proof)

    for (own, project, iface), seen in sorted(versions.items()):
        matrix = matrices[project]
        if len(seen) > 1:
            listed = "; ".join(f"{v}: {', '.join(s)}" for v, s in sorted(seen.items()))
            errors.append(
                f"{project} {iface}: claiming {own} scripts pin different "
                f"{matrix.interfaces[iface].package} versions ({listed})"
            )
        tested = next(iter(seen)) if len(seen) == 1 and own == project else None
        for ev in matrix.evidence:
            verified = ev.verified.get(iface)
            if tested and verified and verified != tested:
                warnings.append(
                    f"evidence.yml: {iface} {', '.join(ev.journeys)} was "
                    f"verified with {verified}, scripts now pin {tested}; re-verify"
                )

    for key, cell in proofs.items():
        # The matrix's own project first, so its proof is the one a cell shows.
        # A rollup shows its best member: the SQL working beats Python failing.
        rollup = bool(catalog.interfaces[key[1]].rollup)
        cell.sort(
            key=lambda p: (rollup and not p.claim.works, p.project != key[0], p.script)
        )
        ready = [p for p in cell if p.ready]
        if not rollup and len({p.claim.works for p in ready}) > 1:
            project, iface, journey = key
            errors.append(
                f"{project} {iface} {journey}: scripts disagree whether it works "
                f"({', '.join(p.script for p in ready)})"
            )
    for project, matrix in matrices.items():
        for ev in matrix.evidence:
            for iface in ev.interfaces:
                for journey in ev.journeys:
                    ready = [
                        p for p in proofs.get((project, iface, journey), []) if p.ready
                    ]
                    if not ready:
                        continue
                    proven = ready[0]
                    if proven.claim.works == (ev.outcome == "works"):
                        warnings.append(
                            f"evidence.yml: evidence for {iface} {journey} "
                            f"is redundant; {proven.script} proves it"
                        )
                    else:
                        errors.append(
                            f"evidence.yml: evidence says {iface} {journey} "
                            f"{ev.outcome}, but {proven.script} proves otherwise"
                        )
    # A catalog fact checked from each matrix that shows it is reported once.
    return Result(
        catalog=catalog,
        matrices=matrices,
        model=model,
        proofs=proofs,
        errors=list(dict.fromkeys(errors)),
        warnings=list(dict.fromkeys(warnings)),
    )


# --- cells --------------------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class Cell:
    """What a matrix says about one interface doing one journey."""

    # tested | fails | missing | documented | unknown
    status: str
    draft: bool  # only a draft page's claim says so
    proofs: tuple[Proof, ...]  # the ones counted, the shown one first
    evidence: tuple[Evidence, ...]

    @property
    def shown(self) -> Proof | None:
        return self.proofs[0] if self.proofs else None


def cell(
    result: Result, matrix: Matrix, iface: str, journey: str, *, drafts: bool
) -> Cell:
    """A cell's status. Ready claims beat draft claims (counted only with
    ``drafts``), which beat evidence."""
    every = result.proofs.get((matrix.project, iface, journey), [])
    evidence = tuple(
        e for e in matrix.evidence if iface in e.interfaces and journey in e.journeys
    )
    counted = [p for p in every if p.ready] or (
        [p for p in every if not p.ready] if drafts else []
    )
    if counted:
        works = counted[0].claim.works
        return Cell(
            status="tested" if works else "fails",
            draft=not counted[0].ready,
            proofs=tuple(p for p in counted if p.claim.works == works),
            evidence=evidence,
        )
    if evidence:
        outcome = evidence[0].outcome
        return Cell(
            status="documented" if outcome == "works" else outcome,
            draft=False,
            proofs=(),
            evidence=evidence,
        )
    return Cell(status="unknown", draft=False, proofs=(), evidence=())


# --- rendering ----------------------------------------------------------------


def _header(iface: Interface, matrix: Matrix) -> str:
    label = iface.label
    if iface.pin and iface.pin in matrix.pins:
        label += " " + ".".join(matrix.pins[iface.pin].split(".")[:2])
    return f"[{label}](model:{iface.model})" if iface.model else label


def _evidence_link(
    ev: Evidence, matrix: Matrix, embed: Path, content_root: Path
) -> str | None:
    page, _ = _source_page(ev.source, content_root)
    if page is None:
        return ev.source
    # A private page never ships, so only another private page may link it.
    if page_status(page) == "private" and page_status(embed) != "private":
        return None
    return _link(page, ev.source.partition("#")[2] or None, embed, content_root)


def _render_cell(
    found: Cell,
    iface: str,
    matrix: Matrix,
    table: Table,
    embed: Path,
    content_root: Path,
    detailed: bool,
) -> str:
    """One cell. ``detailed`` (a private page) adds draft markers, the API, and
    evidence links, and always shows documented cells."""
    if found.status == "unknown" or (
        found.status == "documented" and not (table.documented or detailed)
    ):
        return "—"
    shown = found.shown
    link: str | None = None
    if shown is not None:
        anchored = (
            shown
            if shown.claim.works
            else next((p for p in found.proofs if p.anchor), None)
        )
        if anchored is not None:
            link = _link(anchored.page, anchored.anchor, embed, content_root)
        note, api = shown.claim.note, shown.claim.api
    else:
        ev = found.evidence[0]
        note, api = ev.note, ev.api.get(iface)
        if found.status == "documented" or detailed:
            link = _evidence_link(ev, matrix, embed, content_root)
    symbol = {"tested": "✓", "documented": "docs"}.get(found.status, "✗")
    parts = [f"[{symbol}]({link})" if link else symbol]
    if detailed and api:
        parts.append(f"`{api}`")
    if note:
        parts.append(note)
    if detailed and found.draft:
        parts.append("(draft)")
    return " ".join(parts)


def render(
    result: Result, matrix: Matrix, table: Table, embed: Path, content_root: Path
) -> list[str]:
    """The table's Markdown lines for a page that embeds it."""
    detailed = page_status(embed) == "private"
    ifaces = [matrix.interfaces[c] for c in table.columns if c in matrix.interfaces]
    lines = [
        "| Operation | " + " | ".join(_header(i, matrix) for i in ifaces) + " |",
        "| --- |" + " --- |" * len(ifaces),
    ]
    for row in table.rows:
        journey = matrix.journeys[row]
        label = f"{journey.title} (`{row}`)" if detailed else journey.title
        cells = [
            _render_cell(
                cell(result, matrix, i.key, row, drafts=detailed),
                i.key,
                matrix,
                table,
                embed,
                content_root,
                detailed,
            )
            for i in ifaces
        ]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return lines


def render_interfaces(
    result: Result, matrix: Matrix, embed: Path, content_root: Path
) -> list[str]:
    """A model/evidence summary for every authored compatibility interface."""

    def refs(ids: list[str]) -> str:
        return (
            ", ".join(
                f"[{result.model.titles.get(eid, eid)}](model:{eid})" for eid in ids
            )
            or "—"
        )

    lines = [
        "| Interface | Implementation | Contracts | Modeled breadth | Verified here |",
        "| --- | --- | --- | --- | --- |",
    ]
    for iface in matrix.interfaces.values():
        label = _versioned_label(result, matrix, iface)
        model_id = iface.model

        def link(e: str) -> str:
            return f"[{result.model.titles.get(e, e)}](model:{e})"

        implementation = link(model_id) if model_id else "—"
        if iface.integrations:
            implementation += " with " + ", ".join(map(link, iface.integrations))
        contracts = _contracts(result, iface)
        modeled_assets = sorted(
            target
            for kind, source, target in result.model.edges
            if source == model_id and kind == "operatesOn"
        )
        proven: dict[str, list[tuple[str, Proof]]] = {}
        for journey in matrix.journeys.values():
            proofs = result.proofs.get((matrix.project, iface.key, journey.id), [])
            ready = next(
                (proof for proof in proofs if proof.ready and proof.claim.works),
                None,
            )
            if ready is not None and journey.asset:
                proven.setdefault(journey.asset, []).append((journey.id, ready))
        verified = []
        for asset, uses in sorted(
            proven.items(), key=lambda item: result.model.titles.get(item[0], item[0])
        ):
            proof = uses[0][1]
            href = _link(proof.page, proof.anchor, embed, content_root)
            title = result.model.titles.get(asset, asset)
            count = len(uses)
            verified.append(
                f"[{title}: {count} journey{'s' if count != 1 else ''}]({href})"
            )
        lines.append(
            "| "
            + " | ".join(
                [
                    label,
                    implementation,
                    refs(contracts),
                    refs(modeled_assets),
                    ", ".join(verified) or "—",
                ]
            )
            + " |"
        )
    return lines


@dataclasses.dataclass(frozen=True)
class Engine:
    """One implementation's interfaces, and the tables that show any of them."""

    id: str  # the interfaces' model element, else the interface key
    title: str
    interfaces: tuple[str, ...]
    groups: tuple[Table, ...]  # columns narrowed to this engine's interfaces


def engines(matrix: Matrix, model: Model) -> list[Engine]:
    """Every engine in interface order. A table's rows apply to an engine when
    its columns show one of the engine's interfaces."""
    keys: dict[str, list[Interface]] = {}
    for iface in matrix.interfaces.values():
        keys.setdefault(iface.model or iface.key, []).append(iface)
    found = []
    for eid, ifaces in keys.items():
        mine = [i.key for i in ifaces]
        groups = tuple(
            dataclasses.replace(t, columns=tuple(c for c in t.columns if c in mine))
            for t in matrix.tables.values()
            if set(t.columns) & set(mine)
        )
        title = model.titles.get(eid) or ifaces[0].label
        found.append(Engine(eid, title, tuple(mine), groups))
    return found


# A journey shows an engine's best cell: a ready answer beats upstream docs,
# which beat a draft page's claim.
_RANK = {"tested": 0, "fails": 1, "missing": 1, "documented": 2, "unknown": 9}


def _best(cells: Iterable[Cell]) -> Cell:
    return min(cells, key=lambda c: _RANK[c.status] + (3 if c.draft else 0))


def _engine_rows(
    result: Result, matrix: Matrix, engine: Engine, *, drafts: bool
) -> list[tuple[Table, list[tuple[Journey, Cell]]]]:
    return [
        (
            group,
            [
                (
                    matrix.journeys[row],
                    _best(
                        cell(result, matrix, i, row, drafts=drafts)
                        for i in group.columns
                    ),
                )
                for row in group.rows
            ],
        )
        for group in engine.groups
    ]


def _engine_pages(
    content_root: Path,
) -> dict[tuple[str, str], tuple[Path, Heading | None]]:
    """(project, engine id) → the page that embeds its report, and the heading
    the report sits under, which names the engine for readers."""
    pages: dict[tuple[str, str], tuple[Path, Heading | None]] = {}
    for page in iter_content_files(content_root):
        text = page.read_text()
        if f"<!-- compat:{_ENGINE}" not in text:
            continue
        project = _project_of(page, content_root) or ""
        for number, line in enumerate(text.split("\n"), start=1):
            m = _OPEN_RE.match(line)
            if m and m.group("table").startswith(_ENGINE):
                key = (project, m.group("table")[len(_ENGINE) :])
                pages.setdefault(key, (page, _section_above(page, number)))
    return pages


def _verified_count(rows: list[tuple[Journey, Cell]]) -> str:
    done = sum(1 for _, c in rows if c.status == "tested" and not c.draft)
    return f"{done} of {len(rows)}"


def render_engine(
    result: Result, matrix: Matrix, engine: Engine, embed: Path, content_root: Path
) -> list[str]:
    """The engine's journeys per table: what an example here verifies, what it
    shows failing, what only upstream docs say, and what no example runs."""
    detailed = page_status(embed) == "private"
    groups = _engine_rows(result, matrix, engine, drafts=detailed)
    lines = [
        f"Verified here: {_verified_count([p for _, r in groups for p in r])} "
        "journeys.",
        "",
        "| Journeys | Verified here | Doesn't work | Upstream docs only "
        "| Not verified here |",
        "| --- | --- | --- | --- | --- |",
    ]
    for group, rows in groups:
        listed: dict[str, list[str]] = {
            "works": [],
            "no": [],
            "docs": [],
            "unknown": [],
        }
        for journey, found in rows:
            if found.status == "unknown":
                listed["unknown"].append(journey.title)
                continue
            shown = found.shown
            href: str | None = None
            if shown is not None:
                anchored = (
                    shown
                    if shown.claim.works
                    else next((p for p in found.proofs if p.anchor), None)
                )
                if anchored is not None:
                    href = _link(anchored.page, anchored.anchor, embed, content_root)
            else:
                href = (
                    _evidence_link(found.evidence[0], matrix, embed, content_root)
                    or None
                )
            # The qualifier a claim or evidence carries ("on local storage").
            note = shown.claim.note if shown is not None else found.evidence[0].note
            label = journey.title + (" (draft)" if found.draft else "")
            linked = f"[{label}]({href})" if href else label
            bucket = {"tested": "works", "documented": "docs"}.get(found.status, "no")
            listed[bucket].append(f"{linked} ({note})" if note else linked)
        lines.append(
            f"| {group.title} ({_verified_count(rows)}) | "
            + " | ".join(", ".join(items) or "—" for items in listed.values())
            + " |"
        )
    return lines


def render_engines(
    result: Result, matrix: Matrix, embed: Path, content_root: Path
) -> list[str]:
    """One row per engine, linking the page that embeds its report."""
    pages = _engine_pages(content_root)
    lines = [
        "| Engine | Interfaces | Verified journeys |",
        "| --- | --- | --- |",
    ]
    for engine in engines(matrix, result.model):
        found = pages.get((matrix.project, engine.id))
        name = engine.title
        if found:
            page, heading = found
            anchor = heading.id if heading else None
            same = page.resolve() == embed.resolve()
            href = f"#{anchor}" if same and anchor else None
            href = href or _link(page, anchor, embed, content_root)
            name = f"[{heading.text if heading else engine.title}]({href})"
        labels = dict.fromkeys(
            _versioned_label(result, matrix, matrix.interfaces[k])
            for k in engine.interfaces
        )
        rows = [
            pair
            for _, group in _engine_rows(result, matrix, engine, drafts=False)
            for pair in group
        ]
        lines.append(f"| {name} | {', '.join(labels)} | {_verified_count(rows)} |")
    return lines


def asset_groups(matrix: Matrix, model: Model) -> list[Table]:
    """One table per asset, in journey order: every tabled journey on it, and
    every interface a table shows it under, in interface order."""
    tabled = {row for t in matrix.tables.values() for row in t.rows}
    order: dict[str, list[str]] = {}
    for journey in matrix.journeys.values():
        if journey.asset and journey.id in tabled:
            order.setdefault(journey.asset, []).append(journey.id)
    groups = []
    for asset, rows in order.items():
        shown = {
            col
            for t in matrix.tables.values()
            if set(t.rows) & set(rows)
            for col in t.columns
        }
        groups.append(
            Table(
                id=f"{_ROLLUP}{asset}",
                title=model.titles.get(asset, asset),
                columns=tuple(k for k in matrix.interfaces if k in shown),
                rows=tuple(rows),
            )
        )
    return groups


def _rollup(
    result: Result, matrix: Matrix, asset: str, embed: Path, content_root: Path
) -> Table | None:
    """The rollup for ``asset`` on ``embed``, without the columns or rows that say
    nothing there (unless every one would go). A matrix tracks journeys nobody
    has tried yet; a rollup reports only what something answers."""
    group = next(
        (t for t in asset_groups(matrix, result.model) if t.id == _ROLLUP + asset),
        None,
    )
    if group is None:
        return None
    detailed = page_status(embed) == "private"

    def says(col: str, row: str) -> bool:
        rendered = _render_cell(
            cell(result, matrix, col, row, drafts=detailed),
            col,
            matrix,
            group,
            embed,
            content_root,
            detailed,
        )
        return rendered != "—"

    speaking = tuple(
        col for col in group.columns if any(says(col, row) for row in group.rows)
    )
    columns = speaking or group.columns
    rows = tuple(row for row in group.rows if any(says(col, row) for col in columns))
    return dataclasses.replace(group, columns=columns, rows=rows or group.rows)


# --- embedding: check and fix -------------------------------------------------


@dataclasses.dataclass
class _Embed:
    page: Path
    table: str
    start: int  # index of the opening marker line
    end: int  # index of the closing marker line


def _embeds(page: Path, lines: list[str], errors: list[str]) -> list[_Embed]:
    found: list[_Embed] = []
    i = 0
    while i < len(lines):
        m = _OPEN_RE.match(lines[i])
        if not m:
            i += 1
            continue
        table = m.group("table")
        close = _CLOSE.format(table=table)
        end = next(
            (j for j in range(i + 1, len(lines)) if lines[j].strip() == close), None
        )
        if end is None:
            errors.append(f"{page}: compat:{table} has no closing `{close}`")
            break
        found.append(_Embed(page=page, table=table, start=i, end=end))
        i = end + 1
    return found


def _rendered(
    repo_root: Path, result: Result, errors: list[str]
) -> Iterable[tuple[Path, list[str], list[str]]]:
    """Each page that embeds a table: its current lines and its rendered lines."""
    content_root = repo_root / "content"
    embedded: dict[tuple[str, str], list[Path]] = {}
    for page in iter_content_files(content_root):
        text = page.read_text()
        if "<!-- compat:" not in text:
            continue
        lines = text.split("\n")
        new = list(lines)
        project = _project_of(page, content_root) or ""
        matrix = result.matrices.get(project)
        # Replace from the bottom up so earlier indices stay valid.
        for embed in reversed(_embeds(page, lines, errors)):
            summary = embed.table in (_INTERFACES, _ENGINES) or embed.table.startswith(
                _ENGINE
            )
            if summary:
                if matrix is None:
                    errors.append(
                        f"{page}: compat:{embed.table} has no matrix in "
                        f"content/{project}/{FILE}"
                    )
                    continue
                if embed.table == _INTERFACES:
                    body = render_interfaces(result, matrix, page, content_root)
                elif embed.table == _ENGINES:
                    body = render_engines(result, matrix, page, content_root)
                else:
                    eid = embed.table[len(_ENGINE) :]
                    engine = next(
                        (e for e in engines(matrix, result.model) if e.id == eid),
                        None,
                    )
                    if engine is None:
                        errors.append(
                            f"{page}: compat:{embed.table}: no interface in "
                            f"content/{project}/{FILE} has model {eid}"
                        )
                        continue
                    body = render_engine(result, matrix, engine, page, content_root)
                embedded.setdefault((project, embed.table), []).append(page)
                source = posixpath.relpath(
                    f"{project}/{FILE}",
                    posixpath.dirname(_page_route(page, content_root)),
                )
                new[embed.start : embed.end + 1] = [
                    _OPEN.format(table=embed.table, source=source),
                    *body,
                    _CLOSE.format(table=embed.table),
                ]
                continue
            if matrix is not None and embed.table.startswith(_ROLLUP):
                asset = embed.table[len(_ROLLUP) :]
                table = _rollup(result, matrix, asset, page, content_root)
                if table is None:
                    errors.append(
                        f"{page}: compat:{embed.table}: no tabled journey in "
                        f"content/{project}/{FILE} acts on {asset}"
                    )
                    continue
            else:
                table = matrix.tables.get(embed.table) if matrix else None
            if matrix is None or table is None:
                errors.append(
                    f"{page}: compat:{embed.table} is not a table in "
                    f"content/{project}/{FILE}"
                )
                continue
            embedded.setdefault((project, embed.table), []).append(page)
            body = render(result, matrix, table, page, content_root)
            source = posixpath.relpath(
                f"{project}/{FILE}", posixpath.dirname(_page_route(page, content_root))
            )
            new[embed.start : embed.end + 1] = [
                _OPEN.format(table=embed.table, source=source),
                *body,
                _CLOSE.format(table=embed.table),
            ]
        yield page, lines, new
    for (project, tid), pages in sorted(embedded.items()):
        if len(pages) > 1:
            errors.append(
                f"{project} tables.{tid} is embedded more than once: "
                + ", ".join(str(p) for p in pages)
            )
    for project, matrix in sorted(result.matrices.items()):
        for tid in matrix.tables:
            if (project, tid) not in embedded:
                result.warnings.append(
                    f"{matrix.path.name}: tables.{tid} is on no page"
                )


